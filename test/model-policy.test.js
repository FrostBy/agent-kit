'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { resolve } = require('../src/agents/model-policy');
test('policy applies global permissions, project restrictions and priority', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-policy-')); t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const env = { HOME: root }, cwd = path.join(root, 'repo', 'nested'); fs.mkdirSync(cwd, { recursive: true }); fs.mkdirSync(path.join(root, 'repo', '.git'));
  const global = path.join(root, '.config', 'agent-kit', 'agents.json'), project = path.join(root, 'repo', '.agent-kit', 'agents.json');
  const write = (file, value) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, JSON.stringify(value)); };
  assert.equal(resolve({ env, cwd }).connector, 'codex');
  const executable = path.join(root, 'opencode.exe');
  write(global, { priority: ['opencode', 'codex'], connectors: { opencode: { enabled: true, models: ['one', 'two'], executable }, codex: { enabled: true, models: ['allowed'] } } });
  assert.throws(() => resolve({ env, cwd }), /explicit model/);
  assert.equal(resolve({ env, cwd, model: 'one' }).agent, 'opencode');
  assert.equal(resolve({ env, cwd, model: 'one' }).executable, executable);
  assert.throws(() => resolve({ env, cwd, connector: 'opencode', model: 'other' }), /not allowed/);
  assert.throws(() => resolve({ env, cwd, connector: 'codex', model: 'other' }), /not allowed/);
  assert.throws(() => resolve({ env, cwd, connector: 'codex' }), /not allowed/);
  write(global, { connectors: { codex: { models: [] } } });
  assert.throws(() => resolve({ env, cwd, connector: 'codex', model: 'allowed' }), /not allowed/);
  write(global, { priority: ['opencode', 'codex'], connectors: { opencode: { enabled: true, models: ['one', 'two'] }, codex: { enabled: true, models: ['allowed'] } } });
  write(project, { priority: ['codex', 'opencode'], connectors: { codex: { enabled: false }, opencode: { models: ['two'] } } });
  assert.equal(resolve({ env, cwd, model: 'two' }).connector, 'opencode');
  assert.throws(() => resolve({ env, cwd, connector: 'codex' }), /disabled/);
  assert.throws(() => resolve({ env, cwd, connector: 'opencode', model: 'one' }), /not allowed/);
  write(project, { connectors: { opencode: { models: ['other'] } } }); assert.throws(() => resolve({ env, cwd, model: 'other' }), /not allowed/);
  write(project, { connectors: { unknown: { enabled: true } } }); assert.throws(() => resolve({ env, cwd }), /Invalid connector/);
  write(project, { connectors: { opencode: { executable: 123 } } }); assert.equal(resolve({ env, cwd, model: 'one' }).executable, undefined);
  write(project, { connectors: { opencode: { models: [] } } }); assert.throws(() => resolve({ env, cwd, connector: 'opencode', model: 'one' }), /not allowed/);
});

test('ancestor policies narrow permissions across a repository boundary', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-ancestors-')); t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const home = root, umbrella = path.join(root, 'umbrella'), repo = path.join(umbrella, 'repo'), cwd = path.join(repo, 'nested');
  fs.mkdirSync(cwd, { recursive: true }); fs.mkdirSync(path.join(repo, '.git'));
  const env = { HOME: home }, global = path.join(home, '.config', 'agent-kit', 'agents.json');
  const policy = dir => path.join(dir, '.agent-kit', 'agents.json');
  const write = (file, value) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, JSON.stringify(value)); };
  assert.equal(resolve({ env, cwd }).connector, 'codex');
  write(global, { connectors: { codex: { models: ['a', 'b', 'c'], executable: 'global-executable' }, kimi: { enabled: false } } });
  write(policy(home), { connectors: { codex: { enabled: false } } });
  write(policy(umbrella), { connectors: { codex: { models: ['a', 'b'] }, kimi: { enabled: true } } });
  assert.equal(resolve({ env, cwd, connector: 'codex', model: 'a' }).executable, 'global-executable');
  assert.throws(() => resolve({ env, cwd, connector: 'codex', model: 'c' }), /not allowed/);
  assert.throws(() => resolve({ env, cwd, connector: 'kimi' }), /disabled/);
  write(policy(repo), { connectors: { codex: { models: ['b', 'c'], executable: 'ignored' } } });
  assert.equal(resolve({ env, cwd, connector: 'codex', model: 'b' }).executable, 'global-executable');
  assert.throws(() => resolve({ env, cwd, connector: 'codex', model: 'a' }), /not allowed/);
  assert.throws(() => resolve({ env, cwd, connector: 'codex', model: 'c' }), /not allowed/);
  write(policy(repo), { connectors: { codex: { enabled: true, models: ['a', 'b', 'c'] } } });
  assert.equal(resolve({ env, cwd, connector: 'codex', model: 'a' }).connector, 'codex');
  assert.throws(() => resolve({ env, cwd, connector: 'codex', model: 'c' }), /not allowed/);
  write(policy(umbrella), { connectors: { codex: { enabled: false } } });
  assert.throws(() => resolve({ env, cwd, connector: 'codex', model: 'a' }), /disabled/);
});
